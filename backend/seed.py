def make_buyers(count: int) -> list[tuple[str, str, str]]:
    """Generate (email, password, full_name) tuples."""
    out = []
    used_emails = set()
    for i in range(count):
        is_female = random.random() < 0.5
        first = random.choice(FIRST_NAMES_F if is_female else FIRST_NAMES_M)
        last = random.choice(LAST_NAMES) + ("а" if is_female else "")
        local = f"{first.lower()}.{last.lower()}{i+1}"
        email = f"{local}@example.com".replace("ё", "e")
        if email in used_emails:
            email = f"{local}.{random.randint(100, 999)}@example.com"
        used_emails.add(email)
        out.append((email, "demo12345", f"{first} {last}"))
    return out


def random_dt_within(days_ago_max: int, days_ago_min: int = 0) -> datetime:
    """Random datetime in the past, biased towards evening hours."""
    now = datetime.utcnow()
    days = random.uniform(days_ago_min, days_ago_max)
    base = now - timedelta(days=days)
    # Bias hours to 9-22 (active hours), with a bump around 18-22
    hour_pool = list(range(9, 23)) * 2 + list(range(18, 23)) * 3
    return base.replace(
        hour=random.choice(hour_pool),
        minute=random.randint(0, 59),
        second=random.randint(0, 59),
        microsecond=0,
    )


